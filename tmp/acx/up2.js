    '        const multi = multiMode || e.metaKey || e.ctrlKey || e.shiftKey',
    '        if (multi) {',
    '          toggleAgent(agent.id)',
    '          return',
    '        }',
    '        store.set({ agentSel: [agent.id], activeAgentId: agent.id })',
    '      }',
